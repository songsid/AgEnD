export function ht(key: Key, ...args: (string | number)[]): string {
  const template = (getLocale() === "zh-TW" ? zhTW : en)[key];
  return template.replace(/\{(\d+)\}/g, (_, i: string) => String(args[Number(i)] ?? ""));
}
