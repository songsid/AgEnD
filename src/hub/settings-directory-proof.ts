type Actor = HubDirectoryDecisionRequest["actor"];
export interface HubDirectoryProofContext {
  /** Produced by the configured-admin route or the hostSessionHere/D3 adapter, NEVER decoded from the request body. */
  actor: Actor;
  current(): boolean;
  signal?: AbortSignal;
}
export interface HubDirectoryProofSource {
  directory: HubDirectory;
  config: HubDirectoryConfig;
  bindPassword: string;
  administrator: PersonKey;
  groups: readonly DirectoryPolicyGroup[];
  epoch: number;
  /** Full current seal/material + settings/policy/lifecycle/version image, generated by the composition. */
  image: string;
  current(): boolean;
}
export interface HubDirectoryProofDeps {
  source(): HubDirectoryProofSource;
  /** The SAME composition-shared physical-promise 4/person, 32/total pool; not a new private budget. */
  withDirectoryRead<T>(subject: PersonKey, work: () => Promise<T>): Promise<T>;
  createDirectory(config: HubDirectoryConfig, secrets: { bindPassword: string }, options: { expectedServerFingerprint?: string }): HubDirectory;
  writer(): HubDirectorySettingsWriter;
  /** Optional SERVER attestation from the current HubSessions row's AD sign-in, not a client timestamp. */
  recentAuthentication?(actor: Extract<Actor, { kind: "hub-administrator" }>): number | null;
  now?(): number;
  /** Inert tests only; production uses the verified TLS probe below. */
  probeTls?(config: ResolvedDirectoryConfig): Promise<string>;
}
export type HubDirectoryProofCode = "invalid" | "denied" | "reauthentication" | "unavailable" | "busy" | "stale" | "expired" | "trust";
export class HubDirectoryProofError extends Error {
  constructor(readonly code: HubDirectoryProofCode) { super(code); this.name = "HubDirectoryProofError"; }
}
function refuse(code: HubDirectoryProofCode): never { throw new HubDirectoryProofError(code); }
const same = (a: unknown, b: unknown) => canonicalArguments(a) === canonicalArguments(b);
const TTL = 5 * 60_000, MAX_DRAFTS = 32, ATTEMPT_WINDOW = TTL;
const fp = (s: string) => s.replace(/:/g, "").toUpperCase();
const fingerprint = (s: string): string => { const value = fp(s); return /^[0-9A-F]{64}$/.test(value) ? value : refuse("unavailable"); };
const opaqueSecret = (s: unknown): s is string => typeof s === "string" && !!s && scalarString(s) && Buffer.byteLength(s) <= 4096;
function boolean(check: () => boolean): boolean {
  const result: unknown = check();
  if (result && (typeof result === "object" || typeof result === "function") && typeof (result as { then?: unknown }).then === "function") {
    try { (result as PromiseLike<unknown>).then(undefined, () => undefined); } catch { /* denied below */ }
    return false;
  }
  return result === true;
}
const actorKey = ({ requestId: _requestId, ...actor }: Actor) => canonicalArguments(actor);
function caFingerprints(cfg: HubDirectoryConfig, now: number, old = false): string[] {
  if (cfg.caPem === undefined) return [];
  try {
    if (!old) return directoryCaInfo(cfg.caPem, now).certificates.map(c => fingerprint(c.fingerprint256)).sort();
    // A sealed OLD CA may have expired: D3 must still be able to replace it. Parse its identity, never trust it anew.
    const pems = pemCertificates(cfg.caPem);
    if (Buffer.byteLength(cfg.caPem) > 64 * 1024 || !pems.length || pems.length > 4
      || cfg.caPem.replace(/-----BEGIN CERTIFICATE-----[\s\S]*?-----END CERTIFICATE-----/g, "").trim()) refuse("invalid");
    return pems.map(pem => { const cert = new X509Certificate(pem); if (!cert.ca) refuse("invalid"); return fingerprint(cert.fingerprint256); }).sort();
  } catch { return refuse("invalid"); }
}

/** Normal TLS verification BEFORE any LDAP/application bytes; settle only after the owned socket physically closes. */
export function probeHubDirectorySettingsTls(cfg: ResolvedDirectoryConfig): Promise<string> {
  return new Promise((resolve, reject) => {
    const socket = connect({ host: cfg.host, port: cfg.port, ...(isIP(cfg.host) ? {} : { servername: cfg.host }),
      ...(cfg.caPem === undefined ? {} : { ca: cfg.caPem }), rejectUnauthorized: true, minVersion: "TLSv1.2" });
    let result: string | undefined, failed = false;
    const timeout = setTimeout(() => { failed = true; socket.destroy(); }, cfg.timeoutMs);
    socket.on("error", () => { failed = true; });
    socket.once("secureConnect", () => {
      try {
        const cert = socket.getPeerCertificate();
        if (!socket.authorized || !socket.encrypted || !cert.raw || cert.raw.length > 64 * 1024) throw Error();
        result = fingerprint(new X509Certificate(cert.raw).fingerprint256);
      } catch { failed = true; }
      socket.destroy();
    });
    socket.once("close", () => { clearTimeout(timeout); if (failed || !result) reject(new HubDirectoryProofError("unavailable")); else resolve(result); });
  });
}

interface CapturedSource extends HubDirectoryProofSource { resolved: ResolvedDirectoryConfig }
interface Draft {
  actor: Actor; source: CapturedSource; candidate: HubDirectorySettingsCandidate; resolved: ResolvedDirectoryConfig;
  createdAt: number; expiresAt: number; leaf: string; ca: string[]; trustRequired: boolean; challenge: string;
}
export interface HubDirectorySettingsProof {
  prepare(candidate: HubDirectorySettingsCandidate, context: HubDirectoryProofContext): Promise<{
    ref: string; expiresAt: number; trust: null | { challenge: string; server: string; leafFingerprint: string; caFingerprints: string[]; systemRoots: boolean };
  }>;
  test(ref: string, confirmation: string | undefined, context: HubDirectoryProofContext): Promise<void>;
  apply(ref: string, input: { confirmation?: string; credentials?: { login: string; password: string } }, context: HubDirectoryProofContext, rotation?: HubDirectorySessionRotation, beforeCommit?: () => void | number): Promise<{ receiptId: string; directoryEpoch: number }>;
  cancel(ref: string, context: HubDirectoryProofContext): void;
  close(): void;
}

export function createHubDirectorySettingsProof(deps: HubDirectoryProofDeps): HubDirectorySettingsProof {
  const now = deps.now ?? Date.now, probe = deps.probeTls ?? probeHubDirectorySettingsTls;
  const drafts = new Map<string, Draft>(), recent = new Map<string, { image: string; epoch: number; at: number }>();
  const attempts = new Map<string, { at: number; count: number }>();
  let stopped = false, preparing = 0;
  const time = () => { const t = now(); return Number.isSafeInteger(t) && t >= 0 ? t : refuse("expired"); };
  const context = (input: HubDirectoryProofContext) => {
    const actor = parseHubDirectoryDecisionMetadata({ actor: input.actor, changes: ["search"], recipients: [{ kind: "host", sink: "owner" }] }).actor;
    // Capture callback/signal and nested identity before any await; later input replacement cannot retarget a proof.
    return { actor, current: input.current, signal: input.signal };
  };
  const capture = (): CapturedSource => {
    const s = deps.source(), config = structuredClone(s.config), administrator = validated(person, s.administrator);
    const groups = structuredClone(s.groups);
    if (!/^[a-f0-9]{64}$/.test(s.image) || !Number.isSafeInteger(s.epoch) || s.epoch < 0 || !opaqueSecret(s.bindPassword)
      || groups.length > 32 || groups.some(g => !person.safeParse(g.key).success || g.key.realm !== administrator.realm)) refuse("unavailable");
    const resolved = resolveDirectoryConfig(config);
    if (resolved.realm !== administrator.realm || s.directory.realm !== administrator.realm) refuse("unavailable");
    return { ...s, config, administrator, groups, resolved };
  };
  const current = (d: Pick<Draft, "source" | "actor" | "createdAt" | "expiresAt">, ctx: ReturnType<typeof context>) => {
    const t = time();
    if (stopped || ctx.signal?.aborted || actorKey(ctx.actor) !== actorKey(d.actor) || !boolean(ctx.current) || !boolean(d.source.current)) refuse("denied");
    const s = capture();
    if (!boolean(s.current) || s.directory !== d.source.directory || s.image !== d.source.image || s.epoch !== d.source.epoch
      || !same(s.config, d.source.config) || s.bindPassword !== d.source.bindPassword || !same(s.administrator, d.source.administrator)
      || !same(s.groups, d.source.groups)) refuse("stale");
    // The authority/material callbacks may move the clock too. Last sample follows ALL of them.
    const final = time();
    if (t < d.createdAt || t >= d.expiresAt || final < d.createdAt || final >= d.expiresAt) refuse("expired");
  };
  const admitted = async <T>(d: Draft, ctx: ReturnType<typeof context>, work: () => Promise<T>): Promise<T> => {
    current(d, ctx);
    try {
      const result = await deps.withDirectoryRead(d.source.administrator, async () => { current(d, ctx); return work(); });
      current(d, ctx); return result;
    } catch (error) { current(d, ctx); if (error instanceof HubDirectoryProofError) throw error; refuse("unavailable"); }
  };
  const get = (ref: string, ctx: ReturnType<typeof context>): Draft => { const d = drafts.get(ref); if (!d) refuse("expired"); current(d, ctx); return d; };
  const confirmed = (d: Draft, confirmation: string | undefined) => { if (d.trustRequired && confirmation !== d.challenge) refuse("trust"); };
  const candidate = async (d: Draft, ctx: ReturnType<typeof context>) => admitted(d, ctx, async () => {
    const leaf = fingerprint(await probe(d.resolved)); current(d, ctx);
    if (d.trustRequired && leaf !== d.leaf) refuse("trust");
    let directory: HubDirectory | undefined;
    try {
      directory = deps.createDirectory(structuredClone(d.candidate.directory), { bindPassword: d.candidate.bindPassword! },
        d.trustRequired ? { expectedServerFingerprint: d.leaf } : {});
      if (directory.realm !== d.source.administrator.realm) refuse("denied");
      const checkAdmin = async () => {
        const answer = await directory!.checkEligibility(Object.freeze({ ...d.source.administrator })); current(d, ctx);
        if (!answer.eligible) refuse(answer.reason === "unavailable" ? "unavailable" : "denied");
        if (!same(answer.person.key, d.source.administrator)) refuse("denied");
      };
      await checkAdmin(); current(d, ctx);
      for (const group of d.source.groups) {
        if (directory.groupPolicy !== "ad-direct-guid" || !directory.checkPolicyGroup) refuse("unavailable");
        const result = await directory.checkPolicyGroup(Object.freeze({ ...group.key })); current(d, ctx);
        if (!result.ok || !same(result.group.key, group.key)) refuse("unavailable");
      }
      if (d.source.groups.length) { await checkAdmin(); current(d, ctx); }
    } finally { await directory?.close(); }
    current(d, ctx);
  });
  const authenticate = async (d: Draft, ctx: ReturnType<typeof context>, credentials?: { login: string; password: string }) => {
    if (ctx.actor.kind === "host-owner") { if (credentials !== undefined) refuse("invalid"); return d.createdAt; }
    const key = actorKey(ctx.actor), stored = recent.get(key);
    const attested = stored?.image === d.source.image && stored.epoch === d.source.epoch ? stored.at : deps.recentAuthentication?.(ctx.actor);
    current(d, ctx);
    const t = time();
    if (credentials === undefined && attested !== undefined && attested !== null && Number.isSafeInteger(attested) && attested >= 0 && attested <= t && t - attested < TTL) {
      await admitted(d, ctx, async () => {
        const answer = await d.source.directory.checkEligibility(Object.freeze({ ...d.source.administrator })); current(d, ctx);
        if (!answer.eligible) refuse(answer.reason === "unavailable" ? "unavailable" : "denied");
        if (!same(answer.person.key, d.source.administrator)) refuse("denied");
      });
      return attested;
    }
    if (!credentials) refuse("reauthentication");
    if (typeof credentials.login !== "string" || !credentials.login.trim() || credentials.login.length > 256
      || typeof credentials.password !== "string" || !credentials.password || credentials.password.length > 1024 || !scalarString(credentials.password)) refuse("invalid");
    const previous = attempts.get(key);
    if (previous && t < previous.at) refuse("expired");
    if (previous && t - previous.at >= 0 && t - previous.at < ATTEMPT_WINDOW && previous.count >= 5) refuse("busy");
    for (const [id, a] of attempts) if (t - a.at >= ATTEMPT_WINDOW) attempts.delete(id);
    if (!previous && attempts.size >= 1024) refuse("busy");
    const window = previous && t - previous.at < ATTEMPT_WINDOW ? previous : { at: t, count: 0 };
    window.count++; attempts.set(key, window);
    const authenticatedAt = time();
    let failure = false;
    try {
      await admitted(d, ctx, async () => {
        // Personal password has exactly ONE destination: the already mounted, trusted OLD directory.
        const answer = await d.source.directory.signIn(credentials.login.trim(), credentials.password); current(d, ctx);
        if (!answer.ok) refuse(answer.reason === "unavailable" ? "unavailable" : "denied");
        if (!same(answer.person.key, d.source.administrator)) refuse("denied");
      });
    } catch (error) { failure = error instanceof HubDirectoryProofError && error.code === "denied"; throw error; }
    finally { if (!failure && attempts.get(key) === window && --window.count === 0) attempts.delete(key); }
    for (const [id, r] of recent) if (time() - r.at >= TTL) recent.delete(id);
    if (!recent.has(key) && recent.size >= 1024) recent.delete(recent.keys().next().value!);
    recent.set(key, { image: d.source.image, epoch: d.source.epoch, at: authenticatedAt });
    return authenticatedAt;
  };
  return {
    async prepare(input, inputContext) {
      const ctx = context(inputContext), source = capture(), createdAt = time(), copy = structuredClone(input);
      if (Object.keys(copy).some(key => !["directory", "bindPassword", "changes", "recipients"].includes(key))) refuse("invalid");
      const metadata = parseHubDirectoryDecisionMetadata({ actor: ctx.actor, changes: copy.changes, recipients: copy.recipients });
      const resolved = resolveDirectoryConfig(copy.directory);
      if (ctx.actor.kind === "hub-administrator" && !same(ctx.actor.person, source.administrator)) refuse("denied");
      if (resolved.realm !== source.resolved.realm || resolved.profile !== source.resolved.profile
        || copy.directory.bindPasswordRef !== undefined && copy.directory.bindPasswordRef !== BIND_PASSWORD_REF) refuse("invalid");
      if (copy.bindPassword === undefined) {
        if (copy.directory.url !== source.config.url || copy.directory.caPem !== source.config.caPem || copy.directory.bindDn !== source.config.bindDn) refuse("invalid");
        copy.bindPassword = source.bindPassword;
      }
      if (!opaqueSecret(copy.bindPassword)) refuse("invalid");
      const ca = caFingerprints(copy.directory, createdAt), oldCa = caFingerprints(source.config, createdAt, true);
      const d: Draft = { actor: metadata.actor, source, candidate: { ...copy, changes: metadata.changes, recipients: metadata.recipients }, resolved, createdAt, expiresAt: createdAt + TTL,
        leaf: "", ca, trustRequired: resolved.url !== source.resolved.url || !same(ca, oldCa), challenge: randomBytes(32).toString("base64url") };
      current(d, ctx);
      for (const [ref, old] of drafts) if (old.expiresAt <= createdAt) drafts.delete(ref);
      if (drafts.size + preparing >= MAX_DRAFTS) refuse("busy");
      preparing++;
      try { d.leaf = fingerprint(await admitted(d, ctx, () => probe(resolved))); }
      finally { preparing--; }
      current(d, ctx);
      const ref = randomBytes(24).toString("base64url"); drafts.set(ref, d);
      return { ref, expiresAt: d.expiresAt, trust: d.trustRequired ? { challenge: d.challenge, server: resolved.url, leafFingerprint: d.leaf,
        caFingerprints: [...d.ca], systemRoots: copy.directory.caPem === undefined } : null };
    },
    async test(ref, confirmation, inputContext) { const ctx = context(inputContext), d = get(ref, ctx); confirmed(d, confirmation); await candidate(d, ctx); },
    async apply(ref, input, inputContext, rotation, beforeCommit) {
      const ctx = context(inputContext), d = get(ref, ctx), credentials = input.credentials && { ...input.credentials }, confirmation = input.confirmation;
      drafts.delete(ref); // Failed and cancelled saves also consume this exact preparation.
      confirmed(d, confirmation);
      const at = await authenticate(d, ctx, credentials); current(d, ctx);
      // Reuse only the current old-directory authentication; never the earlier candidate test as an allowance.
      d.expiresAt = Math.min(d.expiresAt, at + TTL);
      await candidate(d, ctx); current(d, ctx);
      const writer = deps.writer(), proof = () => { current(d, ctx); return true; };
      const prepared = writer.prepare(structuredClone(d.candidate), ctx.actor, proof);
      const effect: unknown = beforeCommit?.();
      if (effect && (typeof effect === "object" || typeof effect === "function") && typeof (effect as { then?: unknown }).then === "function") {
        try { (effect as PromiseLike<unknown>).then(undefined, () => undefined); } catch { /* refused below */ }
        refuse("invalid");
      }
      if (effect !== undefined && typeof effect !== "number") refuse("invalid");
      current(d, ctx);
      return typeof effect === "number" ? writer.commit(prepared.ref, ctx.actor, proof, rotation, effect) : writer.commit(prepared.ref, ctx.actor, proof, rotation);
    },
    cancel(ref, inputContext) { const ctx = context(inputContext); get(ref, ctx); drafts.delete(ref); },
    close() { stopped = true; drafts.clear(); recent.clear(); attempts.clear(); },
  };
}
